// Included by check_playback.py after unchanged production functions.
int main() {
    PlayerJsonLines protocol;
    assert(protocol.append("plain log\n\n{\"FF_ER").empty());
    auto received = protocol.append("ROR\":{\"code\":-1}}\n{\"J\":{\"ms\":2}}\n");
    assert(received.size() == 2);
    assert(protocol.append(std::string(70000, 'x') + "\n{\"ok\":1}\n").size() == 1);
    LiveRecovery vod;
    assert(vod.processExited() == 0);
    LiveRecovery recoveryLive;
    recoveryLive.configure(true, 2);
    assert(recoveryLive.processExited() == 2000);
    assert(recoveryLive.processExited() == 0); // duplicate exit cannot queue two retries
    assert(recoveryLive.consumeRetry());
    assert(recoveryLive.processExited() == 4000);
    assert(recoveryLive.consumeRetry());
    assert(recoveryLive.processExited() == 0); // exhausted budget
    LiveRecovery switched;
    switched.configure(true, 5);
    assert(switched.processExited() > 0);
    switched.stop();
    assert(!switched.consumeRetry());
    assert(switched.processExited() == 0);
    g_GstPlayerOptionsServiceMP3 = new GstPlayerOptions();
    g_GstPlayerOptionsServiceGst = new GstPlayerOptions();
    g_GstPlayerOptionsUser = new GstPlayerOptions();
    g_ExtEplayer3OptionsServiceMP3 = new ExtEplayer3Options();
    g_ExtEplayer3OptionsServiceExt3 = new ExtEplayer3Options();
    g_ExtEplayer3OptionsUser = new ExtEplayer3Options();
    g_ServiceAppOptionsServiceMP3 = new eServiceAppOptions();
    g_ServiceAppOptionsServiceGst = new eServiceAppOptions();
    g_ServiceAppOptionsServiceExt3 = new eServiceAppOptions();
    g_ServiceAppOptionsUser = new eServiceAppOptions();
    assert(effectivePlaybackProfile(PROFILE_AUTO, "https://host/Live.TS?token=x.m3u8") == PROFILE_TS);
    assert(effectivePlaybackProfile(PROFILE_AUTO, "https://host/live.m3u8#sapp_profile=hls") == PROFILE_HLS);
    assert(effectivePlaybackProfile(PROFILE_AUTO, "/recordings/movie.ts") == PROFILE_VOD);
    assert(effectivePlaybackProfile(PROFILE_AUTO, "https://host/live?format=.ts") == PROFILE_VOD);
    assert(effectivePlaybackProfile(PROFILE_AUTO, "https://example.ts") == PROFILE_VOD);
    assert(effectivePlaybackProfile(PROFILE_HLS, "https://host/token") == PROFILE_HLS);
    assert(playbackProfile("typo") == -1);

    ExtEplayer3Options ext;
    assert(ext.update("audio_uri", "https://host/audio path") == 0);
    assert(ext.update("audio_uri", "") == -2);
    assert(ext.update("audio_uri", std::string("a\0b", 3)) == -2);
    assert(ext.update("nice", "-20") == 0);
    assert(ext.update("nice", "20") == -2);
    assert(ext.update("mpegts_program_id", "-1") == -2);
    assert(ext.update("mpegts_program_id", "999999999999999999999999") == -2);
    assert(ext.update("nice", "") == -2);
    assert(ext.update("progressive", "2") == -2);
    assert(ext.update("progressive", "1") == 0);
    assert(ext.update("aac_swdec", "2") == 0);
    assert(ext.update("ffmpeg_option", "rw_timeout=10000000;reconnect_delay_max=4") == 0);
    assert(ext.update("ffmpeg_option", "missing") == -2);
    assert(ext.update("ffmpeg_option", "key=value;") == -2);
    ExtEplayer3 player(ext);
    player.mPath = "https://host/stream with spaces.ts";
    player.mHeaders["User-Agent"] = "test agent";
    auto args = player.buildCommand();
    auto f = std::find(args.begin(), args.end(), "-f");
    assert(f != args.end() && *(f+1) == "rw_timeout=10000000" && *(f+2) == "-f" && *(f+3) == "reconnect_delay_max=4");
    auto o = std::find(args.begin(), args.end(), "-o");
    assert(o != args.end() && *(o+1) == "1");
    assert(std::find(args.begin(), args.end(), "https://host/audio path") != args.end());
    assert(std::find(args.begin(), args.end(), "test agent") != args.end());
    GstPlayerOptions gst;
    assert(gst.update("buffer_size", "") == -2);
    assert(gst.update("buffer_size", "999999999999999999999") == -2);
    gst.openpliInterface = true;
    gst.update("download_buffer_path", "/media/hdd/a path-XXXXXX");
    gst.update("ring_buffer_maxsize", "32");
    GstPlayer gp(gst);
    gp.mPath = "https://host/movie";
    gp.mHeaders["User-Agent"] = "test agent";
    args = gp.buildCommand();
    assert((args == std::vector<std::string>{"gstplayer_gst-1.0", "https://host/movie", "-1", "0", "0",
        "/media/hdd/a path-XXXXXX", "32", "0", "8192", "User-Agent=test agent"}));
    gst.openpliInterface = false;
    GstPlayer legacy(gst);
    args = legacy.buildCommand();
    auto p = std::find(args.begin(), args.end(), "-p");
    assert(p != args.end() && *(p+1) == "/media/hdd/a path-XXXXXX");
    eServiceReference ref{5002, "https://host/channel.ts?token=test"};
    auto cfg = g_ServiceAppOptionsServiceExt3;
    cfg->playback.profile = PROFILE_AUTO;
    std::unique_ptr<BasePlayer> live(createPlayer(ref, HeaderMap()));
    assert(dynamic_cast<ExtEplayer3 *>(live.get())->mPlayerOptions.GetSettingMap()[EXT3_PLAYBACK_LIVETS].getValueInt() == 1);
    HeaderMap headers;
    headers["sapp_live_ts"] = "0";
    headers["sapp_profile"] = "ts";
    live.reset(createPlayer(ref, headers));
    assert(dynamic_cast<ExtEplayer3 *>(live.get())->mPlayerOptions.GetSettingMap()[EXT3_PLAYBACK_LIVETS].getValueInt() == 0);
    ref.path = "https://host/channel.m3u8";
    live.reset(createPlayer(ref, HeaderMap()));
    assert(dynamic_cast<ExtEplayer3 *>(live.get())->mPlayerOptions.GetSettingMap()[EXT3_PLAYBACK_LIVETS].getValueInt() == 0);
    std::unique_ptr<eServiceAppOptions> so(createOptions(ref));
    assert(!so->HLSExplorer);
    cfg->playback.hlsExplorer = true;
    so.reset(createOptions(ref));
    assert(so->HLSExplorer);
    cfg->playback.profile = PROFILE_LEGACY;
    so.reset(createOptions(ref));
    assert(so->HLSExplorer);
    ref.type = 5001;
    cfg = g_ServiceAppOptionsServiceGst;
    cfg->playback.profile = PROFILE_AUTO;
    cfg->playback.tsBufferSize = 2048;
    cfg->playback.hlsBufferSize = 16384;
    cfg->playback.hlsBufferDuration = 5;
    g_GstPlayerOptionsServiceGst->update("download_buffer_path", "/media/hdd/XXXXXX");
    g_GstPlayerOptionsServiceGst->update("ring_buffer_maxsize", "32");
    live.reset(createPlayer(ref, HeaderMap()));
    auto gm = &dynamic_cast<GstPlayer *>(live.get())->mPlayerOptions.GetSettingMap();
    assert((*gm)[GST_BUFFER_SIZE].getValueInt() == 16384 && (*gm)[GST_BUFFER_DURATION].getValueInt() == 5);
    assert(!(*gm)[GST_DOWNLOAD_BUFFER_PATH].isSet() && !(*gm)[GST_RING_BUFFER_MAXSIZE].isSet());
    ref.path = "https://host/channel.ts";
    live.reset(createPlayer(ref, HeaderMap()));
    assert(dynamic_cast<GstPlayer *>(live.get())->mPlayerOptions.GetSettingMap()[GST_BUFFER_SIZE].getValueInt() == 2048);
    headers.clear();
    headers["sapp_buffer_size"] = "4096";
    live.reset(createPlayer(ref, headers));
    assert(dynamic_cast<GstPlayer *>(live.get())->mPlayerOptions.GetSettingMap()[GST_BUFFER_SIZE].getValueInt() == 4096);
    cfg->playback.profile = PROFILE_VOD;
    live.reset(createPlayer(ref, HeaderMap()));
    gm = &dynamic_cast<GstPlayer *>(live.get())->mPlayerOptions.GetSettingMap();
    assert((*gm)[GST_BUFFER_SIZE].getValueInt() == 8192 && (*gm)[GST_RING_BUFFER_MAXSIZE].isSet());
    assert(g_GstPlayerOptionsServiceGst->GetSettingMap()[GST_BUFFER_SIZE].getValueInt() == 8192);
    g_useUserSettings = true;
    g_ServiceAppOptionsUser->playback.profile = PROFILE_TS;
    g_ServiceAppOptionsUser->playback.tsBufferSize = 1024;
    live.reset(createPlayer(ref, HeaderMap()));
    assert(dynamic_cast<GstPlayer *>(live.get())->mPlayerOptions.GetSettingMap()[GST_BUFFER_SIZE].getValueInt() == 1024);
    std::cout << "C++ option, argv, profile, precedence and buffer checks passed\n";
}
